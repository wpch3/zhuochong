/* Data-level tests for the independent local zrig editor. */
'use strict';
const assert = require('assert');
const fs = require('fs');
const {Session} = require('../tools/rig_editor/core.js');
const source = JSON.parse(fs.readFileSync('experiments/live2d_chibi_human_short/rig.json', 'utf8'));
const sourceJson = JSON.stringify(source);
const s = new Session(source);
assert.throws(() => new Session({}), /zrig/);
const malformed = JSON.parse(sourceJson); malformed.parts[0].tags = 42;
assert.throws(() => new Session(malformed), /结构/);
const badDeformers = JSON.parse(sourceJson); badDeformers.deformers = [null];
assert.throws(() => new Session(badDeformers), /结构/);
badDeformers.deformers = {}; assert.throws(() => new Session(badDeformers), /结构/);
assert.throws(() => s.addParameter('ParamAngleX', '内建', -1, 1, 0), /内建/);
assert.throws(() => s.addParameter('invalid', '错误', -1, 1, 0), /参数 ID/);
assert.throws(() => s.addParameter('Param' + 'a'.repeat(35), '过长', -1, 1, 0), /参数 ID/);
assert.throws(() => s.addParameter('ParamWrong', '错误', -1, 1, 2), /范围/);
assert.throws(() => s.setPart('head', NaN, 0, 0), /有限/);
const socketRig = JSON.parse(sourceJson); socketRig.parts[0].socket = 's_anchor';
assert.throws(() => new Session(socketRig).setPart('body', 10, 10, 10), /挂点/);
assert.throws(() => s.addGroupBind('ParamMouthOpenY', 'head', 'alpha', 1, 0), /不支持/);
assert.strictEqual(s.history.length, 0, 'errors must not create history or mutate');
s.addParameter('ParamEditorHead', '编辑器测试', -1, 1, 0);
assert.throws(() => s.addParameter('ParamEditorHead', '重复', -1, 1, 0), /已存在/);
assert.throws(() => s.addGroupBind('ParamEditorHead', 'missing', 'rot_deg', 4, 0), /不存在/);
s.addGroupBind('ParamEditorHead', 'head', 'rot_deg', 4, 0);
assert.deepStrictEqual(s.rig.params.at(-1).binds, [{group:'head', param:'rot_deg', scale:4, offset:0}]);
const originalHead = [...s.rig.parts.find(p => p.id === 'head').pos];
s.setPart('head', originalHead[0] + 2, originalHead[1], 30);
assert.strictEqual(s.rig.parts.find(p => p.id === 'head').pos[0], originalHead[0] + 2);
assert(s.undo()); assert.deepStrictEqual(s.rig.parts.find(p => p.id === 'head').pos, originalHead);
assert(s.redo()); assert.strictEqual(s.rig.parts.find(p => p.id === 'head').pos[0], originalHead[0] + 2);
assert(s.undo());
s.removeBind('ParamEditorHead', 0); assert.strictEqual(s.rig.params.at(-1).binds.length, 0);
assert(!s.redo(), 'new edit must discard redo history');
assert(s.undo()); assert.strictEqual(s.rig.params.at(-1).binds.length, 1);
s.addParameter('ParamEditorMesh', '网格测试', 0, 1, 0);
assert.throws(() => s.addKeyform('head', 'body', 'ParamEditorMesh', 2, 2), /重复/);
assert.throws(() => s.addKeyform('bad', 'body', 'ParamEditorMesh', 17, 2), /网格/);
const chained = JSON.parse(sourceJson); chained.parts.find(p => p.id === 'body').deformer = 'some_parent';
chained.params.push({id:'ParamTestMesh',min:0,max:1,default:0,binds:[]});
assert.throws(() => new Session(chained).addKeyform('mesh_test','body','ParamTestMesh',2,2), /挂接/);
const threeKey = new Session(source); threeKey.addParameter('ParamThree', '三键', -1, 1, 0); threeKey.addKeyform('mesh_three','body','ParamThree',2,2);
assert.deepStrictEqual(threeKey.rig.deformers[0].keys.map(k => k.v), [-1,0,1]);
s.addKeyform('editor_mesh', 'body', 'ParamEditorMesh', 2, 2);
assert.throws(() => s.addKeyform('another_mesh', 'body', 'ParamEditorMesh', 2, 2), /已有网格/);
assert.throws(() => s.setKeyformPoint('editor_mesh', 1, 3, 0, 5, 0), /越界/);
assert.throws(() => s.setKeyformPoint('editor_mesh', 0.5, 0, 0, 5, 0), /关键值不存在/);
s.setKeyformPoint('editor_mesh', 1, 0, 0, 25, 0);
assert.deepStrictEqual(s.rig.deformers.at(-1).keys, [{v:0,points:[]},{v:1,points:[{c:0,r:0,dx:25,dy:0}]}]);
assert(s.undo()); assert.strictEqual(s.rig.deformers.at(-1).keys[1].points.length, 0);
assert(s.redo()); assert.strictEqual(s.rig.deformers.at(-1).keys[1].points[0].dx, 25);
assert.strictEqual(JSON.stringify(source), sourceJson, 'source object must not be mutated');
// Create an actual parent-child group, attach a non-socket part and bind it.
assert.throws(() => s.addGroup('1bad','head',0,0), /组 ID/);
assert.throws(() => s.addGroup('editor_bone','missing',0,0), /父组/);
assert.throws(() => s.addGroup('head','root',0,0), /重复/);
assert.throws(() => s.addGroup('finite_test','root',NaN,0), /有限/);
const fullGroups = JSON.parse(sourceJson); for (let i=0; Object.keys(fullGroups.groups).length<63; i++) fullGroups.groups['g'+i]={pivot:[0,0],parent:'root'};
assert.throws(() => new Session(fullGroups).addGroup('too_many','root',0,0), /上限/);
s.addGroup('editor_bone','head',512,400);
s.addGroup('editor_child','editor_bone',512,410);
assert.throws(() => s.setGroup('editor_bone','editor_child',512,400), /父组/);
assert.throws(() => s.setGroup('root','head',0,0), /root/);
assert.throws(() => new Session(socketRig).setPartGroup('body','head'), /挂点/);
s.setGroup('editor_child','head',513,412); assert.strictEqual(s.rig.groups.editor_child.parent,'head');
assert(s.undo()); assert.strictEqual(s.rig.groups.editor_child.parent,'editor_bone');
s.setPartGroup('nose','editor_bone'); assert.strictEqual(s.rig.parts.find(p=>p.id==='nose').group,'editor_bone');
assert(s.undo()); assert.strictEqual(s.rig.parts.find(p=>p.id==='nose').group,'head'); assert(s.redo());
s.addParameter('ParamEditorBone', '骨骼测试', -1, 1, 0);s.addGroupBind('ParamEditorBone','editor_bone','dx',12,0);
const roundtrip = JSON.parse(s.serialize());
assert.deepStrictEqual(roundtrip.params.find(p => p.id === 'ParamEditorHead').binds, [{group:'head', param:'rot_deg', scale:4, offset:0}]);
assert.deepStrictEqual(roundtrip.deformers.at(-1), s.rig.deformers.at(-1));
assert.deepStrictEqual(roundtrip.actions, source.actions, 'unknown fields must survive');
if (process.argv[2]) fs.writeFileSync(process.argv[2], s.serialize());
console.log('zrig 编辑器：事务、内建参数、通道校验、撤销重做和 JSON 往返通过');
