'use strict';
const assert = require('assert');
const fs = require('fs');
const v = require('../tools/rig_editor/viewport.js');
const rig = JSON.parse(fs.readFileSync('tools/rig_editor/demo.json', 'utf8'));
assert.strictEqual(v.safePath('sprites/head.png'), 'sprites/head.png');
for (const path of ['../evil', '/etc/passwd', 'sprites/../../bad', 'sprites\\bad', '']) assert.throws(() => v.safePath(path));
const shown = v.visible(rig).map(p => p.id);
assert(shown.includes('eye_l_open') && !shown.includes('eye_l_closed'));
assert(shown.includes('mouth_rest') && !shown.includes('mouth_speak'));
const geo = v.geometry({pos:[100,200], anchor:[0.5,0.5], scale:0.5}, {width:80,height:40}, rig);
assert.deepStrictEqual(geo, {x:100,y:200,w:40,h:20,ax:20,ay:10,angle:0});
assert(v.contains(geo, 110, 200)); assert(!v.contains(geo, 121, 200));
const turn = v.geometry({pos:[0,0], anchor:[0,0], rot_deg:90}, {width:10,height:20}, rig);
assert(v.contains(turn, -10, 5)); assert(!v.contains(turn, 5, 5));
const events = {};
const ctx = {clearRect(){}, save(){}, restore(){}, translate(){}, rotate(){}, drawImage(){},
  setLineDash(){}, strokeRect(){}, beginPath(){}, arc(){}, fill(){}, moveTo(){}, lineTo(){}, stroke(){}};
const canvas = {width:0,height:0, addEventListener(k, f){events[k]=f}, getContext(){return ctx},
  getBoundingClientRect(){return {left:0,top:0,width:1024,height:1024}}, setPointerCapture(){}};
let move = null;
const view = new v.Viewport(canvas, (id,pos,layer) => { move = {id,pos,layer}; }, () => {});
view.setRig(rig, false);
view.images.set('sprites/body.png', {width:480,height:512});
view.setSelection('body');
events.pointerdown({button:0,pointerId:1,clientX:400,clientY:500,preventDefault(){}});
events.pointermove({pointerId:1,clientX:420,clientY:530});
events.pointerup({pointerId:1});
assert.deepStrictEqual(move, {id:'body',pos:[300,488],layer:10});
const socketRig = JSON.parse(JSON.stringify(rig)); socketRig.parts[0].socket = 'fixed';
view.setRig(socketRig, false); view.setSelection('body'); move = null;
events.pointerdown({button:0,pointerId:1,clientX:400,clientY:500,preventDefault(){}});
events.pointermove({pointerId:1,clientX:420,clientY:530}); events.pointerup({pointerId:1});
assert.strictEqual(move, null, 'socket-controlled parts must not drag');
const mesh = {id:'mesh',part:'body',param:'ParamTest',cols:2,rows:2,keys:[{v:0,points:[]},{v:1,points:[{c:2,r:0,dx:10,dy:2}]}]};
const rotated = {id:'body',pos:[100,200],anchor:[.5,.5],scale:[2,3],rot_deg:90};
const img = {width:80,height:40};
const points = v.meshPoints(rotated,img,rig,mesh,1);
assert(Math.abs(points[2].x - 154) < 1e-9 && Math.abs(points[2].y - 300) < 1e-9);
const delta = v.sourceDelta(v.geometry(rotated,img,rig),img,6,4);
assert(Math.abs(delta[0] - 2) < 1e-9 && Math.abs(delta[1] + 2) < 1e-9);
assert.strictEqual(v.meshPoints({...rotated,socket:'a'},img,rig,mesh,1), null);
assert.strictEqual(v.meshPoints(rotated,img,rig,{...mesh,w:[1]},1), null);
assert.strictEqual(v.meshPoints(rotated,img,rig,mesh,0.5), null);
const meshRig = JSON.parse(JSON.stringify(rig)); meshRig.deformers = [mesh];
let edit = null;
const meshView = new v.Viewport(canvas, () => { throw Error('must not move part in mesh mode'); }, () => {},
  (id,value,c,r,dx,dy) => { edit = {id,value,c,r,dx,dy}; });
meshView.setRig(meshRig,false); meshView.images.set('sprites/body.png',{width:480,height:512});
meshView.setSelection('body'); meshView.setMesh('mesh',0,true);
events.pointerdown({button:0,pointerId:7,clientX:520,clientY:714,preventDefault(){}});
events.pointermove({pointerId:8,clientX:800,clientY:800}); events.pointercancel({pointerId:8});
events.pointermove({pointerId:7,clientX:530,clientY:734}); events.pointerup({pointerId:8});
assert.strictEqual(edit,null,'other pointers must not commit/cancel the active drag');
events.pointerup({pointerId:7});
assert.deepStrictEqual(edit,{id:'mesh',value:0,c:1,r:1,dx:10,dy:20});
edit = null; events.pointerdown({button:0,pointerId:7,clientX:520,clientY:714,preventDefault(){}});
events.pointermove({pointerId:7,clientX:530,clientY:734}); events.pointercancel({pointerId:7}); events.pointerup({pointerId:7});
assert.strictEqual(edit,null,'cancel must not commit');
let groupMove = null;
const groupView = new v.Viewport(canvas, () => { throw Error('must not move part in group mode'); }, () => {}, () => {},
  (id,pos) => { groupMove = {id,pos}; });
groupView.setRig(rig,false); groupView.setGroup('head',true);
events.pointerdown({button:0,pointerId:3,clientX:512,clientY:457,preventDefault(){}});
events.pointermove({pointerId:3,clientX:532,clientY:467}); events.pointerup({pointerId:3});
assert.deepStrictEqual(groupMove, {id:'head',pos:[532,467]});
groupMove = null; groupView.setGroup('root',true);
events.pointerdown({button:0,pointerId:3,clientX:512,clientY:946,preventDefault(){}});
events.pointermove({pointerId:3,clientX:532,clientY:956}); events.pointerup({pointerId:3});
assert.strictEqual(groupMove,null,'root cannot be moved');
groupView.setGroup('head',true);
events.pointerdown({button:0,pointerId:3,clientX:512,clientY:457,preventDefault(){}});
events.pointermove({pointerId:3,clientX:532,clientY:467}); events.pointercancel({pointerId:3}); events.pointerup({pointerId:3});
assert.strictEqual(groupMove,null,'cancel cannot commit group drag');
assert.throws(() => view.setRig({canvas:{w:99999,h:3}}, true), /4096/);
console.log('zrig 画布：默认可见层、路径安全、坐标与拖动/挂点保护通过');
